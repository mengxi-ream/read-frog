/** The rows to keep, moved to tags, and the ids of the rows to drop. */
export function moveGlossaryTermsToTags(terms: any[]): { kept: any[]; droppedIds: any[] } {
  const byKey = new Map<string, any>()
  for (const term of terms) {
    const code = term.targetLang
    const targetLang =
      typeof code === "string" && Object.hasOwn(TAG_BY_CODE, code) ? TAG_BY_CODE[code] : code
    const moved = { ...term, targetLang }
    const key = `${moved.glossaryId}\u0000${targetLang}\u0000${moved.matchKey}`
    const kept = byKey.get(key)
    // The newer row wins, the later one on a tie. `Number`, not `getTime()`: a
    // row without a valid date must not throw here.
    if (kept === undefined || Number(moved.updatedAt) >= Number(kept.updatedAt)) {
      byKey.set(key, moved)
    }
  }
  const kept = [...byKey.values()]
  const keptIds = new Set(kept.map((term) => term.id))
  return { kept, droppedIds: terms.filter((term) => !keptIds.has(term.id)).map((term) => term.id) }
}
